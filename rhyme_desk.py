from pathlib import Path
import re
import pronouncing

# Use the first dictionary pronunciation for a simple syllable estimate.
def count_syllables(word):
    sounds = pronouncing.phones_for_word(word)
    if sounds:
        return pronouncing.syllable_count(sounds[0])
    return None


# Keep each word's count visible when checking a practice line.
def check_line(line, target):
    words = re.findall(r"[a-z]+(?:'[a-z]+)?", line.lower().replace("’", "'"))
    counts = [count_syllables(word) for word in words]
    details = [f"{word}={count if count is not None else '?'}"
               for word, count in zip(words, counts)]
    if not words or None in counts:
        verdict = "Count unresolved: an empty line or unknown word."
    else:
        total = sum(counts)
        verdict = f"{total} syllables; target {target}; difference {total - target:+d}"
    ending = words[-1] if words else ""
    return verdict, " / ".join(details), ending


# Ask for a seed and target; pressing Enter uses the demonstration values.
seed = input("Seed word [light]: ").strip().lower() or "light"
target = int(input("Syllables per line [8]: ").strip() or "8")
max_word_syllables = 2
home = Path(__file__).resolve().parent
vocabulary = (home / "wordbank/words.txt").read_text(encoding="utf-8").split()
lines = (home / "wordbank/practice.txt").read_text(encoding="utf-8").splitlines()

# Keep dictionary rhymes that also occur in the small word bank.
rhymes = set(pronouncing.rhymes(seed))
candidates = []
for word in sorted(set(vocabulary)):
    count = count_syllables(word)
    if word != seed and word in rhymes and count is not None and count <= max_word_syllables:
        candidates.append((word, count))

# Build a plain text session with suggestions and line-by-line explanations.
report = ["RAP-BATTLE HELPER", f"Seed: {seed}", f"Line target: {target}", "",
          f"Rhyme ideas ({len(candidates)} matches, up to {max_word_syllables} syllables):"]
for word, count in candidates:
    report.append(f"  {word:<12} {count}")
if not candidates:
    report.append("  No matches in the word bank for this seed.")
report.extend(["", "Practice lines supplied as input:"])
endings = []
for number, line in enumerate(lines, 1):
    verdict, details, ending = check_line(line, target)
    report.extend([f"\n{number}. {line}", f"   {verdict}", f"   {details}"])
    endings.append(ending)

# Compare line endings in pairs using their first listed pronunciations.
for index in range(0, len(endings) - 1, 2):
    first, second = endings[index:index + 2]
    left = pronouncing.phones_for_word(first)
    right = pronouncing.phones_for_word(second)
    match = "unknown"
    if left and right:
        match = str(pronouncing.rhyming_part(left[0]) == pronouncing.rhyming_part(right[0]))
    report.append(f"\nEnd rhyme: {first} / {second} = {match}")
report.extend(["", "Counts and end-rhyme checks use the first dictionary pronunciation.",
               "Practice lines are read from a file, not generated by this program."])
text = "\n".join(report) + "\n"
print("\n" + text)

# Save readable evidence of this session beside the project.
sessions = home / "Sessions"
sessions.mkdir(exist_ok=True)
(sessions / "session.txt").write_text(text, encoding="utf-8")
rows = ["word\tsyllables"] + [f"{word}\t{count}" for word, count in candidates]
(sessions / "rhymes.tsv").write_text("\n".join(rows) + "\n", encoding="utf-8")
